"""What a strategy is, what it can see, and how its parameters are declared.

docs/plans/trading.md Phase 4: *"the ``Strategy`` protocol: a pydantic
``Params`` model declaring each tunable with its type, range and default, plus
``on_bar(ctx)``. The declared ranges are what Phase 5 sweeps."* Three things
follow from taking the second sentence literally.

**The range lives on the field, not in the sweep launcher.** ``swept()`` is an
ordinary pydantic ``Field`` carrying a low, a high and a step, so the range is
validated on every construction *and* readable as data by anything that wants
the parameter space - Phase 5's sweep, Phase 7's launcher, and the JSON schema
the UI renders. A range that lived in the launcher would be a second
declaration that can disagree with the model, and the disagreement would show
up as a sweep that spends an hour producing runs the model then rejects.

**The context is the entire surface a strategy has.** ``ctx.now``,
``ctx.bars()``, ``ctx.chain()``, ``ctx.portfolio`` - the plan names all four -
plus the two ways to place an order. There is deliberately no handle on the
clock, the history or the broker: those are the three objects through which a
strategy could see a bar it should not or fill on the bar it signalled from,
and the protection is that it is never given one. The lookahead gate is a test
(``tests/test_engine_lookahead.py``) and this is the design that lets the test
be short.

**A strategy is a plain object, constructed from validated params.** No base
class to inherit, no registration decorator with import-order semantics. It has
``on_bar`` and it has ``params``, and the module that defines it exports a
``StrategySpec`` naming it. Phase 7's seed job reads the specs; Phase 5's
worker builds from one. The ask's *"I would generally expect to have to develop
and deploy code to introduce a whole new strategy"* is exactly this: a class is
code and a deploy, a ``param_set`` is data.
"""

